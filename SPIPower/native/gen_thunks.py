#!/usr/bin/env python3
"""Generate proxy thunks + header for forwarding SPIPowerMgr.dll exports.

Reads the real DLL's export table and emits (into <out>, default "."):
  thunks.s      ARM trampolines (one per export). Each tail-jumps into the
                global pointer table g_real[] (filled at runtime from the
                original DLL, so no per-function signature is needed).
  spipower.def  export list (same names, so G3NavHMI.exe resolves by name).
  g_proxy.h     PROXY_COUNT + kProxyNames[] for the C++ side.

Usage: python gen_thunks.py <real_dll> [out_dir]
"""
import sys, os, struct

# Functions intercepted in C++ (intercept.cpp) with known signatures. Their
# thunks branch to proxy_<name> instead of tail-jumping into g_real[].
INTERCEPT = {
    'EngSendTFTBrightnessData',
    'EngSendCarSpeed',
    'SPApi_SendKeyEvent',
    'SPApi_SendExtendKeyEvent',
    'SPApi_SendRotaryEvent',
    'SPApi_SetSkelonton',
    'SPApi_LoadByMain',
    # sound and source (2026-10-17): what the shell and VestaHome send, with the caller's process
    'SPApi_SendRadioAudioHMLData',
    'SPApi_SendRadioAudioBalanceFaderData',
    'SPApi_SendRadioAudioVolData',
    'SPApi_SendMediaSourceSelect',
    'SPApi_SendRadioNaviVoiceGuidance',
    'SPApi_SendRadioIsNaviSourceCouldIn',
    'SPApi_SendRadioNaviMediaMuteStatus',
    'SPApi_SendRadioChangeSource',
    # the radio's lists (2026-10-18): the presets - how the shell saves one is not known yet
    'SPApi_SendListItemControl',
}


def parse_exports(path):
    d = open(path, 'rb').read()
    if d[:2] != b'MZ':
        raise SystemExit('not a PE: ' + path)
    e = struct.unpack_from('<I', d, 0x3c)[0]
    if d[e:e + 4] != b'PE\0\0':
        raise SystemExit('no PE signature')
    coff = e + 4
    nsec = struct.unpack_from('<H', d, coff + 2)[0]
    szopt = struct.unpack_from('<H', d, coff + 16)[0]
    opt = coff + 20
    magic = struct.unpack_from('<H', d, opt)[0]
    dd = opt + (96 if magic == 0x10b else 112)
    exp_rva = struct.unpack_from('<I', d, dd)[0]
    if exp_rva == 0:
        raise SystemExit('no export table')
    so = opt + szopt
    secs = []
    for i in range(nsec):
        o = so + i * 40
        vsz = struct.unpack_from('<I', d, o + 8)[0]
        va = struct.unpack_from('<I', d, o + 12)[0]
        rsz = struct.unpack_from('<I', d, o + 16)[0]
        rp = struct.unpack_from('<I', d, o + 20)[0]
        secs.append((va, max(vsz, rsz), rp))

    def r2o(rva):
        for va, sz, rp in secs:
            if va <= rva < va + sz:
                return rp + (rva - va)
        return None

    o = r2o(exp_rva)
    base = struct.unpack_from('<I', d, o + 16)[0]
    nn = struct.unpack_from('<I', d, o + 24)[0]
    an = struct.unpack_from('<I', d, o + 32)[0]
    ao = struct.unpack_from('<I', d, o + 36)[0]
    names = []
    for i in range(nn):
        nr = struct.unpack_from('<I', d, r2o(an) + i * 4)[0]
        ordw = struct.unpack_from('<H', d, r2o(ao) + i * 2)[0]
        no = r2o(nr)
        nm = d[no:d.find(b'\0', no)].decode('latin1')
        names.append((base + ordw, nm))
    names.sort()
    return [nm for _, nm in names]


def main():
    real = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else '.'
    names = parse_exports(real)
    n = len(names)

    asm = ['; generated by gen_thunks.py -- do not edit',
           '    AREA |.text|, CODE, READONLY',
           '    IMPORT g_real']
    for i, nm in enumerate(names):
        if nm in INTERCEPT:
            asm.append('    IMPORT proxy_%s' % nm)
            asm.append('    EXPORT %s' % nm)
            asm.append('|%s| PROC' % nm)
            asm.append('    b  proxy_%s' % nm)
            asm.append('    ENDP')
        else:
            asm.append('    EXPORT %s' % nm)
            asm.append('|%s| PROC' % nm)
            asm.append('    ldr r12, =g_real + %d' % (i * 4))
            asm.append('    ldr r12, [r12]')
            asm.append('    mov pc, r12')
            asm.append('    ENDP')
    asm.append('    LTORG')
    asm.append('    END')
    open(os.path.join(out, 'thunks.s'), 'w').write('\n'.join(asm) + '\n')

    deff = ['LIBRARY SPIPowerMgr', 'EXPORTS']
    for nm in names:
        deff.append('    ' + nm)
    open(os.path.join(out, 'spipower.def'), 'w').write('\n'.join(deff) + '\n')

    h = ['// generated by gen_thunks.py -- do not edit',
         '#ifndef G_PROXY_H',
         '#define G_PROXY_H',
         '#define PROXY_COUNT %d' % n,
         '',
         'extern "C" void* g_real[PROXY_COUNT];',
         'extern int g_logging;',
         '',
         'static const wchar_t* const kProxyNames[PROXY_COUNT] = {']
    for nm in names:
        h.append('    L"%s",' % nm)
    h.append('};')
    h.append('')
    h.append('// indices of intercepted functions (into g_real[] / kProxyNames[])')
    for i, nm in enumerate(names):
        if nm in INTERCEPT:
            h.append('#define IDX_%s %d' % (nm, i))
    h.append('')
    h.append('#endif')
    open(os.path.join(out, 'g_proxy.h'), 'w').write('\n'.join(h) + '\n')

    print('generated thunks.s, spipower.def, g_proxy.h for %d exports (%d intercepted)' % (n, len(INTERCEPT)))


if __name__ == '__main__':
    main()

static void Join(wchar_t* out, const wchar_t* a, const wchar_t* b)
{
    int la = (int)wcslen(a);
    _snwprintf(out, MAX_PATH, L"%s%s%s", a, (la && a[la - 1] == L'\\') ? L"" : L"\\", b);
    out[MAX_PATH - 1] = 0;
}


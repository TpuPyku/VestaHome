// SwDnl reads the cfg with _wfopen(path, L"r") + fwscanf(f, L"%s"), i.e. as an ANSI
// stream of whitespace-separated tokens - mirror the factory file layout exactly.
static int WriteAnsiFile(const wchar_t* path, const char* text)
{
    HANDLE h = CreateFile(path, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    if (h == INVALID_HANDLE_VALUE) return 0;
    DWORD len = (DWORD)strlen(text), w = 0;
    int ok = WriteFile(h, text, len, &w, NULL) && w == len;
    FlushFileBuffers(h);
    CloseHandle(h);
    return ok;
}

// ---------------------------------------------------------- firmware version gate
// Everything below works on the fingerprint table in install/fingerprints.h, which
// tools/gen_fingerprints.py derives from the official 4120 package. Rationale: the
// proxy is rebuilt from one DLL build; another firmware version has a same-size but
// different SPIPowerMgr.dll and would lose its SPI part (or the whole shell) with our
// export table in place.
static void AppendStr(wchar_t* dst, int cap, const wchar_t* src)
{
    int have = (int)wcslen(dst);
    if (have >= cap - 1) return;
    wcsncpy(dst + have, src, cap - 1 - have);
    dst[cap - 1] = 0;
}

static void HexToW(const char* hex, wchar_t* out)
{
    int i;
    for (i = 0; i < 32 && hex[i]; i++) out[i] = (wchar_t)(unsigned char)hex[i];
    out[i] = 0;
}

// 32 hex chars, case-insensitive; an empty reference never matches
static int HexEq(const char* a, const char* b)
{
    int i;
    if (!a || !b || !a[0] || !b[0]) return 0;
    for (i = 0; i < 32; i++) {
        char x = a[i], y = b[i];
        if (x >= 'A' && x <= 'F') x = (char)(x + 32);
        if (y >= 'A' && y <= 'F') y = (char)(y + 32);
        if (x != y) return 0;
    }
    return 1;
}

// MD5 + size of a whole file; 0 = unreadable (missing, locked, short read)
static int FileMd5(const wchar_t* path, char hex[33], unsigned int* sizeOut)
{
    HANDLE h = CreateFile(path, GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
    md5_ctx ctx;
    unsigned char digest[16], buf[16384];
    DWORD size, got = 0;
    unsigned int total = 0;
    int ok = 1;

    if (h == INVALID_HANDLE_VALUE) return 0;
    size = GetFileSize(h, NULL);
    if (size == 0xFFFFFFFF) { CloseHandle(h); return 0; }

    md5_init(&ctx);
    for (;;) {
        if (!ReadFile(h, buf, sizeof(buf), &got, NULL)) { ok = 0; break; }
        if (!got) break;
        md5_update(&ctx, buf, (unsigned int)got);
        total += got;
    }
    CloseHandle(h);
    if (!ok || total != size) return 0;   // never hash a truncated file: it would look "different"

    md5_final(&ctx, digest);
    md5_hex(digest, hex);
    if (sizeOut) *sizeOut = total;
    return 1;
}


// VestaHomeInstall - safe swap/rollback for the SPIPowerMgr proxy on the
// Lada Vesta MMC (Windows CE 6.0, ARM). Follows the reversible-install pattern of
// VestaInstall (toolhelp KillProcess, .bak-style backups, append-only log).
//
// Usage: VestaHomeInstall.exe status | install [p2|p3] [force] | rollback | drill [force] | drill-off
//                            | boot install [p2|p3] [force] | boot rollback | boot-off
//        (no command line arguments -> the GUI at the bottom: the same actions as buttons)
//   UI buttons    -> СТАТУС | УСТАНОВИТЬ | УСТ. + ЛОГ | ТЕСТ ВОССТ. | ОТМЕНИТЬ ЗАДАНИЕ | УДАЛИТЬ | FORCE | ВЫХОД
//                    (УСТАНОВИТЬ / УСТ. + ЛОГ / УДАЛИТЬ use the boot path, see BOOT MODE below)
//   status        -> report current state to VestaHomeInstall.log (SD/USB VestaLogs, else \SDMMC) + a message box:
//                    which DLL is in the app folder, the factory copies, the flag, who is
//                    up (shell / Main.exe / services) and the firmware table
//   install       -> the swap (THE SWAP below): kill every holder of the DLL, back the
//                    factory DLL up, copy the proxy in, verify the copy, set the flag and
//                    let the HU reboot
//   install p2    -> same, but create \SDMMC\SPIPower.on (outbound logging)
//   install p3    -> same, flag on (inbound vtable wrap is also gated by the flag)
//   rollback      -> kill the same holders, restore the factory DLL, delete the flag and
//                    start the shell back (no reboot: the file is written while nothing
//                    maps it, so a fresh Main.exe/G3NavHMI loads the factory DLL)
//   install force -> same as install, but continue (loudly) when the firmware check says
//                    the files are not the 4120 ones - only for a known-good variant
//   drill         -> arm the factory boot updater SwDnl.exe with the harmless marker
//                    package: stage SwDnl_drill.upg + SwDnl.cfg on the SD card and
//                    write one byte 0x02 into \ResidentFlash\SwUpdate.flag; reboot the
//                    HU, then read the verdict with "status"/"drill-off" (../SWDNL.md)
//   drill-off     -> disarm: delete \ResidentFlash\SwUpdate.flag, remove the staged
//                    drill files from the SD and report the drill verdict
//   boot ...      -> arm the swap for the next boot (BOOT MODE below); boot-off = drill-off,
//                    which also removes the boot staging
//
// BOOT MODE - why (2026-10-13/14, ../MAIN.md, ../SWDNL.md): the live install cannot work -
// the running G3NavHMI cannot be killed (TerminateProcess err=170, its threads sit in a
// driver call) and the HU resets while the installer waits. The factory updater does not
// help either: SwDnl.exe kills only HzWD.exe/dr_Service.exe, while Main.exe LoadLibrary()'s
// SPIPowerMgr.dll *before* it checks SwUpdate.flag and stays alive, and SwDnl's unpacker
// opens every file with _wfopen("wb") and aborts the whole package on the first failure -
// so a .upg with the proxy would hit the same lock and leave the flag armed (a boot loop
// into the updater). But Main.exe starts \SDMemory\SwDnl.exe *first* when the flag is set,
// before the shell exists. So "boot" copies this exe there as SwDnl.exe, the proxy and a job
// file to \SDMemory\SPIPower_boot\ and writes SwUpdate.flag=0x02. On the next boot this exe
// runs as SwDnl.exe (no shell, only Main.exe holds the DLL, and Main.exe dies normally):
// it clears the flag and consumes the job *first* (whatever happens next, the following
// boot is a normal one), then runs the very same install/rollback as the live commands.
// Without a job it is a safety net: the proxy in place means Main.exe failed to start the
// shell -> roll back to SPIPowerMgr_orig.dll; anything else -> hand over to the factory
// SwDnl.exe (\ResidentFlash, then \Windows), which still uses the SD rescue package.
//
// Firmware version gate (install/fingerprints.h, generated by tools/gen_fingerprints.py):
// the proxy is built for the exact bytes of one firmware build, so before the swap the
// installer hashes the files it works with and compares them with the official 4120
// package (MAIN/4120/SwDnl.upg) and the 4120 NK image. Other versions ship a different
// SPIPowerMgr.dll - same size, other bytes (the CE emulator tree here has 2e1351...,
// 4120 has 438505b7...) - and swapping that one kills the shell. HARD mismatch = refuse,
// SOFT mismatch = refuse unless "force", INFO = reported only. "status" prints the same
// table, and the MD5 code is proven in place by hashing the proxy and the drill package
// that are already present next to this exe.
//
// THE SWAP - why install is ordered the way it is (../MAIN.md, ../SWDNL.md):
//   \ResidentFlash\navigation\app\SPIPowerMgr.dll is mapped by G3NavHMI.exe *and* by
//   \ResidentFlash\Main.exe, the process that starts the shell: Main.exe LoadLibrary()'s
//   the very same DLL at boot and never unloads it. The loader keeps the image open while
//   any process maps it, so the first version - kill the shell, wait 2.5 s, CreateFile -
//   could not work: the real holder was untouched and the failure returned with the shell
//   still dead. install now:
//   1. kills the shell, Main.exe and AppLauncher.exe and waits for them to be really gone
//      (the lock is released when a process dies, not when TerminateProcess returns),
//      retrying the CreateFile and escalating to the services SwDnl.exe stops before it
//      touches \ResidentFlash (HzWD.exe, dr_Service.exe) only when the file is still busy;
//   2. backs the factory DLL up, copies the proxy in and hashes the file in place against
//      kProxyMd5 - a short or garbled copy is undone right there, while nothing holds it;
//   3. sets the logging flag and asks the MCU for a reset, the same request Main.exe makes
//      through SPApi_SendResetEvent(1) (SPI message id 0x5403). The reboot is unavoidable:
//      a new DLL is only picked up by a fresh shell, and the process that could start one
//      is dead by design. If the request does not go out, the HU still reboots on the MCU's
//      missed heartbeat, and every failure path starts the shell back through Main.exe
//      instead of leaving the HU headless.
//   The live watchdog of the first version went away with the reboot - after the kill there
//   is no shell left to watch. The safety net for a broken proxy is the factory one:
//   Main.exe fails to start the shell 3x, writes SwUpdate.flag=0x02 and lets SwDnl.exe
//   restore the DLL from the SD rescue package (VestaSPIP_install README, step D).
//
// The proxy DLL is taken from this exe's own folder, so the whole SPIPower_install
// folder can live on the SD card as well as on \SDMMC. The factory DLL is preserved
// in two places: SPIPowerMgr_orig.dll (app dir, survives reboot) and
// <SD>\SPIPower_backup\SPIPowerMgr.dll (real SD when present, else \SDMMC).
//
// Mount points (ROM registry, MAIN/4120_unpacked/TINYNK/Registry/default.reg):
//   \SDMemory = StorageManager profile "SDMemory" ("SD Memory Card") -> the SD card
//   \SDMMC    = profiles "MMC"/"MMC2" ("EMMC Disk Drive")            -> internal eMMC
// SwDnl.exe and Main.exe hardcode \SDMemory, so the drill resolves the card at runtime.

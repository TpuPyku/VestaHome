// Verdicts:
//   0 = the files on this unit are the 4120 ones, installing is safe
//   1 = SOFT mismatch: something around the patch is not from 4120 (needs "force")
//   2 = HARD mismatch: the DLL we would replace is not the 4120 build (needs "force")
//   3 = SPIPowerMgr.dll is already the proxy (rollback first)
//   4 = self-test failed: the proxy next to this exe is not the one the exe was built for
// rep gets a human-readable report (log/status/message box); verbose=0 keeps it short.
// Proxies installed by earlier builds of this installer: one of them in place is not "a foreign DLL" but an
// update - the new proxy goes over it, the factory copy (SPIPowerMgr_orig.dll) stays and is checked.
static const char* kOldProxyMd5[] = {
    "fa7b65e000c6f33bbd2f8be18fe85808",   // 2026-10-11 (P1-P3, file log only)
    "0e0a11692af2409dcca273625078222f",   // 2026-10-15 (v2: shared memory, log on \SDMMC)
    "96f4486b5415e194cabb0363009f4dd2",   // 2026-10-17 (log on the SD card, sound/source calls logged)
    "88eb58021d893cdb8e0edf84b3a5feb0",   // 2026-10-18 (shared memory v2, the shell's calls logged too)
    "73dd581b44f77bc7e49edd49195d186a",   // 2026-10-19 (the same sources as now, an earlier build)
};
static const int   kOldProxyN = 5;

static int IsOldProxy(const char* md5)
{
    for (int i = 0; i < kOldProxyN; i++)
        if (HexEq(md5, kOldProxyMd5[i])) return 1;
    return 0;
}

static int InstallCheck(int verbose, wchar_t* rep, int repLen)
{
    int selfFail = 0, alreadyProxy = 0, hardFail = 0, softFail = 0, upgrade = 0;
    int i;
    char md5[33];
    unsigned int size = 0;
    wchar_t line[512], whex[40], src[MAX_PATH];

    rep[0] = 0;
    if (verbose) {
        _snwprintf(line, 512, L"fw:%s эталон: %s\n", kFwName, kFwSrc);
        AppendStr(rep, repLen, line);
    }

    // in-situ self-test of the MD5 code: hash our own artifacts (the proxy that is about
    // to be installed and the drill package) against the generated references. Also
    // catches an installer folder assembled from different builds.
    if (FileExists(g_proxySrc)) {
        if (FileMd5(g_proxySrc, md5, &size)) {
            wchar_t wref[40];
            HexToW(md5, whex);
            HexToW(kProxyMd5, wref);
            if (kProxyMd5[0] && !HexEq(md5, kProxyMd5)) {
                selfFail = 1;
                _snwprintf(line, 512, L"самопроверка: встроенный proxy = %s, эталон %s\n", whex, wref);
            } else {
                _snwprintf(line, 512, L"самопроверка MD5: ok (proxy %s)\n", whex);
            }
        } else {
            _snwprintf(line, 512, L"самопроверка: не удалось прочитать %s\n", g_proxySrc);
        }
        AppendStr(rep, repLen, line);
    }

    Join(src, g_srcDir[0] ? g_srcDir : g_ownDir, kDrillUpg);
    if (FileExists(src) && FileMd5(src, md5, &size)) {
        wchar_t wref[40];
        HexToW(kDrillMd5, wref);
        HexToW(md5, whex);
        if (kDrillMd5[0] && (!HexEq(md5, kDrillMd5) || size != kDrillSize))
            _snwprintf(line, 512, L"самопроверка: %s = %s/%u B, эталон %s/%u\n",
                       kDrillUpg, whex, size, wref, kDrillSize);
        else
            _snwprintf(line, 512, L"самопроверка MD5: ok (%s %s)\n", kDrillUpg, whex);
        AppendStr(rep, repLen, line);
    }

    for (i = 0; i < kFwN; i++) {
        int have = FileMd5(kFw[i].path, md5, &size);
        int match;
        if (!have) {
            _snwprintf(line, 512, L"%s %s: нет доступа\n", TierName(kFw[i].tier), kFw[i].path);
            AppendStr(rep, repLen, line);
            if (kFw[i].tier == FW_HARD) hardFail = 1;
            continue;
        }
        HexToW(md5, whex);
        match = HexEq(md5, kFw[i].md5) && size == kFw[i].size;
        _snwprintf(line, 512, L"%s %s: %s %u B %s\n", TierName(kFw[i].tier), kFw[i].path,
                   whex, size, match ? L"ok" : L"MISMATCH");
        AppendStr(rep, repLen, line);
        if (!match) {
            if (kFw[i].tier == FW_HARD) {
                if (kProxyMd5[0] && HexEq(md5, kProxyMd5)) alreadyProxy = 1;
                else if (IsOldProxy(md5)) {
                    // an update: the factory copy next to it must be the 4120 one, it is what we fall back to
                    char om[33];
                    unsigned int os = 0;
                    if (FileMd5(g_orig, om, &os) && HexEq(om, kFw[i].md5) && os == kFw[i].size) {
                        upgrade = 1;
                        AppendStr(rep, repLen, L"обновление: стоит прежний proxy, SPIPowerMgr_orig.dll = заводская 4120 ok\n");
                    } else {
                        hardFail = 1;
                        AppendStr(rep, repLen, L"обновление: стоит прежний proxy, но SPIPowerMgr_orig.dll не заводская 4120\n");
                    }
                }
                else hardFail = 1;
            } else if (kFw[i].tier == FW_SOFT) {
                softFail = 1;
            }
        }
    }

    {
        int rc = selfFail ? 4 : (alreadyProxy ? 3 : (hardFail ? 2 : (softFail ? 1 : 0)));
        if (verbose) {
            const wchar_t* v;
            if (rc == 4)      v = L"ИТОГ: самопроверка не прошла — папка установщика не та, под которую он собран.\n";
            else if (rc == 3) v = L"ИТОГ: SPIPowerMgr.dll уже наш proxy — сначала удалить (rollback).\n";
            else if (rc == 2) v = L"ИТОГ: SPIPowerMgr.dll не из 4120 (HARD) — proxy собран под 4120, на другой прошивке оболочка не запустится.\n";
            else if (rc == 1) v = L"ИТОГ: часть файлов не из 4120 (SOFT) — install откажет, продолжить на свой риск: install force.\n";
            else if (upgrade) v = L"ИТОГ: стоит прежний proxy — установка его обновит (заводская копия на месте).\n";
            else              v = L"ИТОГ: файлы соответствуют прошивке 4120 — установка безопасна.\n";
            AppendStr(rep, repLen, v);
        }
        return rc;
    }
}


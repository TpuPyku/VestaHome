#!/usr/bin/env python3
"""Generate the Bluetooth proxy's thunks from the real FLC_BLUETOOTH_SDK.dll (as ../native/gen_thunks.py does for
SPIPowerMgr.dll; its export parser is reused).

  thunks.s     one ARM trampoline per export, tail-jumping into g_real[] (no signatures needed); the intercepted
               ones branch to proxy_<name> in bt_proxy.cpp
  flc.def      the same export names, so NCL_BT.DLL resolves them by name
  g_btproxy.h  PROXY_COUNT, kProxyNames[], IDX_<name> for every export (the command thread calls some)

Usage: python gen_thunks_bt.py <real_dll> [out_dir]
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native'))
from gen_thunks import parse_exports

INTERCEPT = {'Flc_Bluetooth_Init', 'Flc_Bluetooth_PbapClient_PullPhonebook'}


def main():
    real = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else '.'
    names = parse_exports(real)
    asm = ['; generated by gen_thunks_bt.py -- do not edit',
           '    AREA |.text|, CODE, READONLY',
           '    IMPORT g_real']
    for i, nm in enumerate(names):
        asm.append('    EXPORT %s' % nm)
        if nm in INTERCEPT:
            asm.insert(3, '    IMPORT proxy_%s' % nm)
            asm.append('|%s| PROC' % nm)
            asm.append('    b  proxy_%s' % nm)
        else:
            asm.append('|%s| PROC' % nm)
            asm.append('    ldr r12, =g_real + %d' % (i * 4))
            asm.append('    ldr r12, [r12]')
            asm.append('    mov pc, r12')
        asm.append('    ENDP')
    asm += ['    LTORG', '    END']
    open(os.path.join(out, 'thunks.s'), 'w').write('\n'.join(asm) + '\n')

    open(os.path.join(out, 'flc.def'), 'w').write(
        '\n'.join(['LIBRARY FLC_BLUETOOTH_SDK', 'EXPORTS'] + ['    ' + nm for nm in names]) + '\n')

    h = ['// generated by gen_thunks_bt.py -- do not edit',
         '#ifndef G_BTPROXY_H',
         '#define G_BTPROXY_H',
         '#define PROXY_COUNT %d' % len(names),
         '',
         'extern "C" void* g_real[PROXY_COUNT];',
         '',
         'static const wchar_t* const kProxyNames[PROXY_COUNT] = {']
    h += ['    L"%s",' % nm for nm in names]
    h += ['};', '']
    h += ['#define IDX_%s %d' % (nm, i) for i, nm in enumerate(names)]
    h += ['', '#endif']
    open(os.path.join(out, 'g_btproxy.h'), 'w').write('\n'.join(h) + '\n')
    print('generated thunks.s, flc.def, g_btproxy.h for %d exports (%d intercepted)' % (len(names), len(INTERCEPT)))


if __name__ == '__main__':
    main()

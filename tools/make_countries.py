#!/usr/bin/env python3
"""make_countries.py - the countries' borders for VestaHome (country.cpp: the country by GPS, the internet radio's
"Рядом"), from Natural Earth's 1:110m admin-0 countries (public domain, naturalearthdata.com).

Usage: python VestaHome/tools/make_countries.py <ne_110m_admin_0_countries.geojson>
  (https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson)
Writes VestaHome/VestaHome/native/countries.inc: every ring's points as hundredths of a degree (short lon, lat),
the rings with their country's ISO code and their box, a country's rings one after another (holes too: the
even-odd count over all of them).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'VestaHome', 'native', 'countries.inc')


def code_of(props):   # France and Norway have ISO_A2 -99, their own code in ISO_A2_EH
    for k in ('ISO_A2', 'ISO_A2_EH'):
        c = props.get(k, '-99')
        if len(c) == 2 and c.isalpha():
            return c.upper()
    return None


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = json.load(open(sys.argv[1], encoding='utf-8'))
    pts, rings = [], []
    for f in sorted(data['features'], key=lambda f: code_of(f['properties']) or ''):
        code = code_of(f['properties'])
        if not code:
            continue
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            for ring in poly:
                q = []
                for lon, lat in ring:
                    p = (int(round(lon * 100)), int(round(lat * 100)))
                    if not q or q[-1] != p:
                        q.append(p)
                if len(q) > 1 and q[0] == q[-1]:
                    q.pop()
                if len(q) < 3:
                    continue
                xs, ys = [p[0] for p in q], [p[1] for p in q]
                rings.append((code, len(pts), len(q), min(xs), max(xs), min(ys), max(ys)))
                pts.extend(q)
    with open(OUT, 'w', encoding='utf-8', newline='\r\n') as o:
        o.write('// countries.inc - generated by VestaHome/tools/make_countries.py from Natural Earth 1:110m admin-0\n')
        o.write('// countries (public domain). Do not edit. %d rings, %d points.\n' % (len(rings), len(pts)))
        o.write('static const short kCountryPt[%d][2] = {\n' % len(pts))
        for i in range(0, len(pts), 8):
            o.write('    ' + ' '.join('{%d,%d},' % p for p in pts[i:i + 8]) + '\n')
        o.write('};\n')
        o.write('static const CountryRing kCountryRing[%d] = {\n' % len(rings))
        for r in rings:
            o.write('    { "%s", %d, %d, %d, %d, %d, %d },\n' % r)
        o.write('};\n')
    print('countries.inc: %d rings, %d points (%d KB)' % (len(rings), len(pts), (len(pts) * 4 + len(rings) * 16) // 1024))


if __name__ == '__main__':
    main()

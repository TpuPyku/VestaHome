"""VestaHome's build of the day (the user 2026-11-28: several builds a day told apart - "1.2.261128.2").

VestaHome's build.bat runs it before compiling:  vh_buildno.py <state file> <header> <source dir>...
The first build of a day is 1 (the version stays "1.2.261128"), a build whose sources changed since the last one
the same day counts on (".2", ".3"...); the same code built again keeps its number. The sources: the top-level
*.cpp / *.c / *.h / *.inc / *.rc of the dirs given (not test_*, not obj/). The header (obj\\vh_buildno.h) gives
VH_BUILDNO / VH_BUILDNO_S to vh_draw.inc's version mark; the state ("YYMMDD n digest") is local, not in git."""
import datetime
import hashlib
import os
import sys

EXTS = ('.cpp', '.c', '.h', '.inc', '.rc')


def next_build(state, today, dig):
    """(day, n, digest) of this build from the last one's (None: none yet)."""
    if not state or state[0] != today:
        return (today, 1, dig)
    if state[2] == dig:
        return state
    return (today, state[1] + 1, dig)


def load(path):
    try:
        day, n, dig = open(path).read().split()
        return (day, int(n), dig)
    except (OSError, ValueError):
        return None


def save(path, state):
    with open(path, 'w', newline='\n') as f:
        f.write('%s %d %s\n' % state)


def header(n):
    return ('// GENERATED by VestaHome/tools/vh_buildno.py: the build of the day (1: the first)\n'
            '#define VH_BUILDNO %d\n#define VH_BUILDNO_S "%d"\n' % (n, n))


def digest(dirs):
    h = hashlib.sha256()
    for d in dirs:
        for name in sorted(os.listdir(d)):
            p = os.path.join(d, name)
            if name.lower().endswith(EXTS) and not name.startswith('test_') and os.path.isfile(p):
                h.update(name.encode('utf-8') + b'\0')
                h.update(open(p, 'rb').read())
    return h.hexdigest()[:16]


def main(argv):
    state_path, header_path, dirs = argv[0], argv[1], argv[2:]
    today = datetime.date.today().strftime('%y%m%d')
    state = next_build(load(state_path), today, digest(dirs))
    save(state_path, state)
    text = header(state[1])
    old = open(header_path).read() if os.path.exists(header_path) else None
    if old != text:   # (unchanged: not rewritten)
        with open(header_path, 'w', newline='\n') as f:
            f.write(text)
    print('VestaHome build of the day: %d' % state[1])


if __name__ == '__main__':
    main(sys.argv[1:])
